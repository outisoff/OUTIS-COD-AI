export function useOrderStats(dateFrom?: Date, dateTo?: Date, filteredOrderIds?: string[] | null, storeId?: string | null, dateField: 'created_at' | 'updated_at' = 'created_at') {
  return useQuery({
    queryKey: ['orders', 'stats', dateFrom?.toISOString(), dateTo?.toISOString(), filteredOrderIds, storeId, dateField],
    queryFn: async () => {
      const hasProductFilter = Array.isArray(filteredOrderIds);
      const startDay = dateFrom ? new Date(dateFrom) : new Date();
      startDay.setHours(0, 0, 0, 0);
      const dayStartISO = startDay.toISOString();
      const endDay = dateTo ? new Date(dateTo) : new Date(startDay);
      endDay.setHours(23, 59, 59, 999);
      const dayEndISO = endDay.toISOString();

      // When user picks "updated_at" basis, override all lifecycle timestamp filters
      // with updated_at so every card reflects "orders touched in this period".
      const col = (lifecycle: string) => dateField === 'updated_at' ? 'updated_at' : lifecycle;
      
      // Get orders whose status changed (updated_at) in the selected period
      let periodOrders: { id: string; status: string; total_price: number }[] = [];
      let page = 0;
      const pageSize = 1000;
      while (true) {
        let query = supabase
          .from('orders')
          .select('id, status, total_price')
          .gte(dateField, dayStartISO)
          .lte(dateField, dayEndISO)
          .range(page * pageSize, (page + 1) * pageSize - 1);
        if (storeId) query = query.eq('store_id', storeId);
        
        const { data: batch, error } = await query;
        if (error) throw error;
        if (batch) periodOrders = periodOrders.concat(batch);
        if (!batch || batch.length < pageSize) break;
        page++;
      }


      // Apply product filter and exclude duplicates
      const filteredOrders = periodOrders.filter(o => {
        if (o.status === 'duplicate') return false;
        if (hasProductFilter && !filteredOrderIds.includes(o.id)) return false;
        return true;
      });

      // Count by current status
      const statusCountMap = new Map<string, number>();
      filteredOrders.forEach(o => {
        statusCountMap.set(o.status, (statusCountMap.get(o.status) || 0) + 1);
      });

      // Snapshot: counts by current status for orders CREATED in the period.
      // Used by the donut charts so totals match "Reçues" (created_at-based).
      const createdStatusCountMap = new Map<string, number>(statusCountMap);

      const pendingStatuses = ['new', 'failed_1', 'failed_2', 'failed_3', 'failed_4', 'failed_5', 'failed_6', 'postponed', 'to_reconfirm', 'callback', 'erreur'] as const;
      const shippedStatuses = ['shipped', 'to_station', 'at_station', 'au_bureau', 'en_livraison'] as const;

      const buildCount = (build: (q: any) => any) => {
        let q: any = supabase.from('orders').select('id', { count: 'exact', head: true });
        q = build(q);
        if (storeId) q = q.eq('store_id', storeId);
        if (hasProductFilter) q = q.in('id', filteredOrderIds!);
        return q;
      };

      // Run all independent count queries in PARALLEL
      const [
        pendingRes,
        confirmedRes,
        cancelledRes,
        duplicateRes,
        preparingRes,
        deliveredRes,
        echecRes,
        totalRes,
      ] = await Promise.all([
        buildCount(q => q.in('status', pendingStatuses).neq('status', 'duplicate').gte(col('pending_at'), dayStartISO).lte(col('pending_at'), dayEndISO)),
        buildCount(q => q.in('status', ['confirmed', 'validated']).gte(col('confirmed_at'), dayStartISO).lte(col('confirmed_at'), dayEndISO)),
        buildCount(q => q.in('status', ['cancelled', 'wrong_number', 'out_of_stock', 'no_answer']).gte(col('cancelled_at'), dayStartISO).lte(col('cancelled_at'), dayEndISO)),
        buildCount(q => q.eq('status', 'duplicate').gte('updated_at', dayStartISO).lte('updated_at', dayEndISO)),
        buildCount(q => q.in('status', ['preparing', 'ready']).gte(col('preparing_at'), dayStartISO).lte(col('preparing_at'), dayEndISO)),
        buildCount(q => q.in('status', ['delivered', 'delivered_paid']).gte(col('delivered_at'), dayStartISO).lte(col('delivered_at'), dayEndISO)),
        buildCount(q => q.in('status', ['Échec_de_livraison', 'returned']).gte(col('returned_at'), dayStartISO).lte(col('returned_at'), dayEndISO)),
        buildCount(q => q.gte(dateField, dayStartISO).lte(dateField, dayEndISO)),
      ]);


      for (const r of [pendingRes, confirmedRes, cancelledRes, duplicateRes, preparingRes, deliveredRes, echecRes, totalRes]) {
        if (r.error) throw r.error;
      }

      const pendingConfirmations = pendingRes.count || 0;
      const confirmedToday = confirmedRes.count || 0;
      const duplicateToday = duplicateRes.count || 0;
      const cancelledToday = (cancelledRes.count || 0) + duplicateToday;
      const preparingToday = preparingRes.count || 0;
      const deliveredToday = deliveredRes.count || 0;
      const echecToday = echecRes.count || 0;
      const totalToday = totalRes.count || 0;
      statusCountMap.set('duplicate', duplicateToday);

      // Rebuild per-status counts for lifecycle groups using their dedicated timestamp columns
      // so drill-down sub-cards stay consistent with the parent card totals.
      const fetchStatusBreakdown = async (
        dateColumn: 'confirmed_at' | 'cancelled_at' | 'preparing_at' | 'shipped_at' | 'delivered_at' | 'delivered_paid_at' | 'returned_at' | 'pending_at',
        statuses: readonly string[]
      ) => {
        const effectiveCol = dateField === 'updated_at' ? 'updated_at' : dateColumn;
        const rows: { status: string }[] = [];
        let p = 0;
        while (true) {
          let q = supabase
            .from('orders')
            .select('status')
            .in('status', statuses as unknown as Database['public']['Enums']['order_status'][])
            .gte(effectiveCol, dayStartISO)
            .lte(effectiveCol, dayEndISO)

            .range(p * pageSize, (p + 1) * pageSize - 1);
          if (storeId) q = q.eq('store_id', storeId);
          if (hasProductFilter) q = q.in('id', filteredOrderIds!);
          const { data, error } = await q;
          if (error) throw error;
          if (data) rows.push(...(data as { status: string }[]));
          if (!data || data.length < pageSize) break;
          p++;
        }
        const counts: Record<string, number> = {};
        statuses.forEach(s => { counts[s] = 0; });
        rows.forEach(r => { counts[r.status] = (counts[r.status] || 0) + 1; });
        Object.entries(counts).forEach(([s, c]) => statusCountMap.set(s, c));
      };

      await Promise.all([
        fetchStatusBreakdown('pending_at', pendingStatuses),
        fetchStatusBreakdown('confirmed_at', ['confirmed', 'validated']),
        fetchStatusBreakdown('cancelled_at', ['cancelled', 'no_answer', 'wrong_number', 'out_of_stock']),
        fetchStatusBreakdown('preparing_at', ['preparing', 'ready']),
        fetchStatusBreakdown('returned_at', ['Échec_de_livraison', 'returned']),
      ]);

      // Livré card breakdown — all sub-cards anchored on delivered_at within period.
      // - Livré: every order delivered within the period (status delivered OR delivered_paid)
      // - Encaissé: subset still unpaid (status='delivered') whose tracking situation
      //   contains "encaiss" or "recouvert"
      // - Payé: subset whose status moved to delivered_paid
      {
        const deliveredRows: { id: string; status: string }[] = [];
        let dp = 0;
        while (true) {
          let dq = supabase
            .from('orders')
            .select('id, status')
            .in('status', ['delivered', 'delivered_paid'] as unknown as Database['public']['Enums']['order_status'][])
            .gte(col('delivered_at'), dayStartISO)
            .lte(col('delivered_at'), dayEndISO)

            .range(dp * pageSize, (dp + 1) * pageSize - 1);
          if (storeId) dq = dq.eq('store_id', storeId);
          if (hasProductFilter) dq = dq.in('id', filteredOrderIds!);
          const { data, error } = await dq;
          if (error) throw error;
          if (data) deliveredRows.push(...(data as { id: string; status: string }[]));
          if (!data || data.length < pageSize) break;
          dp++;
        }

        const deliveredCount = deliveredRows.length;
        const paidCount = deliveredRows.filter(r => r.status === 'delivered_paid').length;

        // For encaisse: among status='delivered' rows, fetch their delivery_situation
        const unpaidIds = deliveredRows.filter(r => r.status === 'delivered').map(r => r.id);
        let encaisseCount = 0;
        if (unpaidIds.length > 0) {
          const sitMap = new Map<string, string>();
          const chunkSize = 500;
          for (let i = 0; i < unpaidIds.length; i += chunkSize) {
            const chunk = unpaidIds.slice(i, i + chunkSize);
            const { data: dels, error: delErr } = await supabase
              .from('deliveries')
              .select('order_id, delivery_situation')
              .in('order_id', chunk);
            if (delErr) throw delErr;
            (dels || []).forEach((d: { order_id: string | null; delivery_situation: string | null }) => {
              if (d.order_id && d.delivery_situation) sitMap.set(d.order_id, d.delivery_situation);
            });
          }
          encaisseCount = unpaidIds.filter(id => {
            const s = (sitMap.get(id) || '').toLowerCase();
            return s.includes('encaiss') || s.includes('recouvert');
          }).length;
        }

        statusCountMap.set('delivered', deliveredCount - paidCount);
        statusCountMap.set('encaisse', encaisseCount);
        statusCountMap.set('delivered_paid', paidCount);
      }

      // Shipping breakdown: for each order, find its LATEST shipping transition
      // (across all time). If that latest transition falls within the selected
      // period, count the order in the sub-card matching that status.
      // → If the order moved on to another shipping status later, it disappears
      //   from the previous day's sub-card.
      {
        // Step 1: candidate orders = anything that EVER reached a shipping status
        // up to dayEndISO. We then keep only those whose LATEST shipping
        // transition falls within [dayStartISO, dayEndISO].
        const candidateIds = new Set<string>();
        let hPage = 0;
        while (true) {
          const { data: hBatch, error: hErr } = await supabase
            .from('order_history')
            .select('order_id')
            .in('new_status', shippedStatuses as unknown as Database['public']['Enums']['order_status'][])
            .gte('created_at', dayStartISO)
            .lte('created_at', dayEndISO)
            .range(hPage * pageSize, (hPage + 1) * pageSize - 1);
          if (hErr) throw hErr;
          (hBatch || []).forEach(r => { if (r.order_id) candidateIds.add(r.order_id); });
          if (!hBatch || hBatch.length < pageSize) break;
          hPage++;
        }

        const subBuckets: Record<string, Set<string>> = {};
        shippedStatuses.forEach(s => { subBuckets[s] = new Set<string>(); });

        if (candidateIds.size > 0) {
          const idsArr = Array.from(candidateIds);
          // Optionally restrict by store/product
          let allowedIds = idsArr;
          if (storeId || hasProductFilter) {
            const allowedSet = new Set<string>();
            const chunk = 500;
            for (let i = 0; i < idsArr.length; i += chunk) {
              let q = supabase
                .from('orders')
                .select('id')
                .in('id', idsArr.slice(i, i + chunk));
              if (storeId) q = q.eq('store_id', storeId);
              const { data: oRows, error: oErr } = await q;
              if (oErr) throw oErr;
              (oRows || []).forEach(o => {
                if (hasProductFilter && !filteredOrderIds!.includes(o.id)) return;
                allowedSet.add(o.id);
              });
            }
            allowedIds = Array.from(allowedSet);
          }

          // For each candidate, fetch its LATEST transition of ANY status.
          // If the latest overall transition is NOT a shipping status (e.g. the
          // order was later delivered or returned), exclude it from shipping
          // sub-buckets entirely.
          const latestStatusByOrder = new Map<string, { status: string; at: string }>();
          const chunk = 200;
          for (let i = 0; i < allowedIds.length; i += chunk) {
            const slice = allowedIds.slice(i, i + chunk);
            let p = 0;
            while (true) {
              const { data: tBatch, error: tErr } = await supabase
                .from('order_history')
                .select('order_id, new_status, created_at')
                .in('order_id', slice)
                .order('created_at', { ascending: false })
                .range(p * pageSize, (p + 1) * pageSize - 1);
              if (tErr) throw tErr;
              (tBatch || []).forEach(r => {
                if (!r.order_id) return;
                const prev = latestStatusByOrder.get(r.order_id);
                if (!prev || new Date(r.created_at).getTime() > new Date(prev.at).getTime()) {
                  latestStatusByOrder.set(r.order_id, { status: r.new_status as string, at: r.created_at });
                }
              });
              if (!tBatch || tBatch.length < pageSize) break;
              p++;
            }
          }

          // Keep only orders whose LATEST transition (any status) is a shipping
          // status AND happened inside the period. If the order moved on to
          // delivered/returned/etc., it disappears from Expédié sub-cards.
          const startMs = new Date(dayStartISO).getTime();
          const endMs = new Date(dayEndISO).getTime();
          const shippedSet = new Set<string>(shippedStatuses as unknown as string[]);
          latestStatusByOrder.forEach((v, orderId) => {
            if (!shippedSet.has(v.status)) return;
            const t = new Date(v.at).getTime();
            if (t >= startMs && t <= endMs && subBuckets[v.status]) {
              subBuckets[v.status].add(orderId);
            }
          });
        }

        shippedStatuses.forEach(s => {
          statusCountMap.set(s, subBuckets[s].size);
        });
      }

      // Expédiées: sum of sub-card counts
      const shippedToday = shippedStatuses.reduce(
        (sum, s) => sum + (statusCountMap.get(s) || 0),
        0,
      );

      // Revenue from delivered orders in the period (includes delivered_paid since they passed through delivered)
      let deliveredOrdersInPeriod: { id: string; total_price: number }[] = [];
      {
        let dPage = 0;
        while (true) {
          let dq = supabase
            .from('orders')
            .select('id, total_price')
            .in('status', ['delivered', 'delivered_paid'])
            .gte(col('delivered_at'), dayStartISO)
            .lte(col('delivered_at'), dayEndISO)

            .range(dPage * pageSize, (dPage + 1) * pageSize - 1);
          if (storeId) dq = dq.eq('store_id', storeId);
          if (hasProductFilter) dq = dq.in('id', filteredOrderIds!);
          const { data: dBatch, error: dErr2 } = await dq;
          if (dErr2) throw dErr2;
          if (dBatch) deliveredOrdersInPeriod = deliveredOrdersInPeriod.concat(dBatch);
          if (!dBatch || dBatch.length < pageSize) break;
          dPage++;
        }
      }
      const revenueToday = deliveredOrdersInPeriod.reduce((sum, o) => sum + Number(o.total_price), 0);

      // Calculate purchase cost for delivered orders
      let chargeToday = 0;
      if (deliveredOrdersInPeriod.length > 0) {
        const deliveredIds = deliveredOrdersInPeriod.map(o => o.id);
        
        const [itemsResult, productsResult] = await Promise.all([
          supabase
            .from('order_items')
            .select('order_id, quantity, product_id')
            .in('order_id', deliveredIds),
          supabase
            .from('products')
            .select('id, purchase_price'),
        ]);

        const deliveredItems = itemsResult.data;
        const products = productsResult.data;

        if (deliveredItems && deliveredItems.length > 0) {
          const purchasePriceMap = new Map<string, number>();
          products?.forEach(p => purchasePriceMap.set(p.id, Number(p.purchase_price)));

          chargeToday = deliveredItems.reduce((sum, item) => {
            const price = item.product_id ? (purchasePriceMap.get(item.product_id) || 0) : 0;
            return sum + (price * item.quantity);
          }, 0);
        }
      }

      // Calculate total products in all orders for the period
      let totalProductsInCommandes = 0;
      if (filteredOrders.length > 0) {
        const orderIds = filteredOrders.map(o => o.id);
        const { data: orderItems } = await supabase
          .from('order_items')
          .select('quantity')
          .in('order_id', orderIds);
        
        totalProductsInCommandes = orderItems?.reduce((sum, item) => sum + item.quantity, 0) || 0;
      }

      // Build ordersByStatus from current status counts
      const ordersByStatus = Array.from(statusCountMap.entries())
        .filter(([, count]) => count > 0)
        .map(([status, count]) => ({ status, count }));

      // ordersByStatusCreated: cohort of orders CREATED in the period, grouped
      // by their current status. Used by donut charts so the totals match
      // "Reçues" (e.g. 34) instead of activity-based totals.
      const ordersByStatusCreated = Array.from(createdStatusCountMap.entries())
        .filter(([, count]) => count > 0)
        .map(([status, count]) => ({ status, count }));

      const pendingCOD = revenueToday;
      
      return {
        totalToday,
        totalCommandes: totalToday,
        totalProductsInCommandes,
        confirmedToday,
        cancelledToday,
        pendingConfirmations,
        preparingToday,
        shippedToday,
        deliveredToday,
        echecToday,
        revenueToday,
        chargeToday,
        pendingCOD,
        ordersByStatus,
        ordersByStatusCreated,
      };
    },
    staleTime: 60_000,
    gcTime: 5 * 60_000,
    refetchOnWindowFocus: false,
    refetchOnMount: false,
  });
}

