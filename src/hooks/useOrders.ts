export function useCreateOrder() {
  const queryClient = useQueryClient();
  
  return useMutation({
    mutationFn: async (data: { 
      order: Omit<OrderInsert, 'order_number' | 'id'>;
      items: Omit<OrderItemInsert, 'order_id'>[];
    }) => {
      // Validate order data
      const validatedOrder = orderInsertSchema.parse(data.order);
      
      // Validate each order item
      const validatedItems = data.items.map(item => orderItemSchema.parse(item));
      
      // Create order - order_number is auto-generated by trigger
      const { data: order, error: orderError } = await supabase
        .from('orders')
        .insert([validatedOrder as OrderInsert])
        .select()
        .single();
      
      if (orderError) throw orderError;
      
      // Create order items
      if (validatedItems.length > 0) {
        const itemsWithOrderId = validatedItems.map(item => ({
          ...item,
          order_id: order.id,
        }));
        
        const { error: itemsError } = await supabase
          .from('order_items')
          .insert(itemsWithOrderId as OrderItemInsert[]);
        
        if (itemsError) throw itemsError;
      }
      
      return order;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['orders'] });
      queryClient.invalidateQueries({ queryKey: ['customers'] });
    },
  });
}

export function useUpdateOrderStatus() {
  const queryClient = useQueryClient();
  
  return useMutation({
    mutationFn: async ({ id, status, notes }: { id: string; status: Order['status']; notes?: string }) => {
      // Validate input
      const validated = orderUpdateStatusSchema.parse({ id, status, notes });
      
      const updates: OrderUpdate = { status: validated.status };
      
      // Set timestamps based on status
      if (validated.status === 'confirmed' || validated.status === 'validated') {
        updates.confirmed_at = new Date().toISOString();
        updates.shipped_at = null;
        updates.delivered_at = null;
      } else if (validated.status === 'shipped' || validated.status === 'at_station') {
        updates.shipped_at = new Date().toISOString();
      } else if (validated.status === 'delivered') {
        updates.delivered_at = new Date().toISOString();
      }
      
      // Clear shipped_at for pre-shipping statuses so they appear in Expedition
      const preShippingStatuses = ['confirmed', 'preparing', 'ready', 'to_station', 'erreur', 'new', 'validated'];
      if (preShippingStatuses.includes(validated.status) && validated.status !== 'confirmed' && validated.status !== 'validated') {
        updates.shipped_at = null;
      }
      
      if (validated.notes) {
        updates.notes = validated.notes;
      }
      
      const { data, error } = await supabase
        .from('orders')
        .update(updates)
        .eq('id', validated.id)
        .select()
        .single();
      
      if (error) throw error;

      // Send tracking notification via WhatsApp (fire and forget)
      supabase.functions.invoke('send-tracking-notification', {
        body: { orderId: validated.id, newStatus: validated.status, trackingNumber: data.tracking_number },
      }).catch(err => console.error('Tracking notification error:', err));

      return data;
    },
    // Optimistic update: patch all matching order caches immediately for instant UI feedback
    onMutate: async ({ id, status, notes }) => {
      const orderKeys = [
        ['orders'],
        ['orders-paginated'],
        ['orders-tracking'],
        ['orders-confirmation'],
        ['orders-expedition'],
        ['orders-paye-retour'],
        ['orders-echange'],
      ];
      // Cancel in-flight refetches so they don't overwrite our optimistic patch
      await Promise.all(orderKeys.map(k => queryClient.cancelQueries({ queryKey: k })));

      const patchOrder = (o: any) => {
        if (!o || o.id !== id) return o;
        const next: any = { ...o, status };
        if (notes) next.notes = notes;
        const nowIso = new Date().toISOString();
        if (status === 'confirmed' || status === 'validated') {
          next.confirmed_at = nowIso;
          next.shipped_at = null;
          next.delivered_at = null;
        } else if (status === 'shipped' || status === 'at_station') {
          next.shipped_at = nowIso;
        } else if (status === 'delivered') {
          next.delivered_at = nowIso;
        }
        return next;
      };

      // Walk every cached query and patch the matching order in-place
      const snapshots: Array<{ queryKey: unknown; data: unknown }> = [];
      orderKeys.forEach(key => {
        const queries = queryClient.getQueriesData({ queryKey: key });
        queries.forEach(([queryKey, data]) => {
          if (!data) return;
          snapshots.push({ queryKey, data });
          // Paginated shape: { orders: [...], totalCount, totalPages }
          if (typeof data === 'object' && data !== null && 'orders' in (data as any) && Array.isArray((data as any).orders)) {
            queryClient.setQueryData(queryKey, {
              ...(data as any),
              orders: (data as any).orders.map(patchOrder),
            });
            return;
          }
          // Plain array of orders
          if (Array.isArray(data)) {
            queryClient.setQueryData(queryKey, data.map(patchOrder));
          }
        });
      });

      return { snapshots };
    },
    onError: (_err, _vars, context) => {
      // Rollback on failure
      context?.snapshots?.forEach(({ queryKey, data }) => {
        queryClient.setQueryData(queryKey as any, data);
      });
    },
    onSettled: () => {
      // Refetch to sync with server (covers timestamps, history, deliveries side-effects)
      queryClient.invalidateQueries({ queryKey: ['orders'] });
      queryClient.invalidateQueries({ queryKey: ['orders-paginated'] });
      queryClient.invalidateQueries({ queryKey: ['orders-tracking'] });
      queryClient.invalidateQueries({ queryKey: ['orders-confirmation'] });
      queryClient.invalidateQueries({ queryKey: ['orders-expedition'] });
      queryClient.invalidateQueries({ queryKey: ['orders-paye-retour'] });
      queryClient.invalidateQueries({ queryKey: ['orders-echange'] });
    },
  });
}

