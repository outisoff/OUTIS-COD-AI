import { supabase } from '@/integrations/supabase/client';
import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import type { Database } from '@/integrations/supabase/types';
import { orderInsertSchema, orderItemSchema, orderUpdateStatusSchema } from '@/lib/validation';
import { z } from 'zod';

type Order = Database['public']['Tables']['orders']['Row'];
type OrderInsert = Database['public']['Tables']['orders']['Insert'];
type OrderUpdate = Database['public']['Tables']['orders']['Update'];
type OrderItem = Database['public']['Tables']['order_items']['Row'];
type OrderItemInsert = Database['public']['Tables']['order_items']['Insert'];

export type OrderWithItems = Order & {
  order_items: OrderItem[];
};

export function useOrders(enabled: boolean = true) {
  return useQuery({
    queryKey: ['orders'],
    queryFn: async () => {
      // Paginate to bypass 1000-row limit
      let allOrders: any[] = [];
      let page = 0;
      const pageSize = 1000;
      while (true) {
        const { data, error } = await supabase
          .from('orders')
          .select(`
            *,
            order_items (
              *,
              products:product_id (sku)
            )
          `)
          .order('created_at', { ascending: false })
          .range(page * pageSize, (page + 1) * pageSize - 1);
        
        if (error) throw error;
        if (data) allOrders = allOrders.concat(data);
        if (!data || data.length < pageSize) break;
        page++;
      }
      return allOrders as OrderWithItems[];
    },
    enabled,
    staleTime: 10 * 60_000,
    gcTime: 30 * 60_000,
    refetchOnWindowFocus: false,
  });
}

export function usePendingOrdersCount(storeId?: string | null, enabled: boolean = true) {
  return useQuery({
    queryKey: ['orders', 'pending-count', storeId],
    queryFn: async () => {
      const pendingStatuses: Order['status'][] = ['new', 'failed_1', 'failed_2', 'callback', 'to_reconfirm'];

      let query = supabase
        .from('orders')
        .select('id', { count: 'exact', head: true })
        .in('status', pendingStatuses);

      if (storeId) {
        query = query.eq('store_id', storeId);
      }

      const { count, error } = await query;
      if (error) throw error;

      return count ?? 0;
    },
    enabled,
    staleTime: 2 * 60_000,
    gcTime: 10 * 60_000,
    refetchOnWindowFocus: false,
  });
}

